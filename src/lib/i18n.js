export function getTranslations(language) {
  return translations[language] ?? translations.en;
}

export function getCoverDescription(level, language) {
  const t = getTranslations(language);
  if (level === "Low") return t.lowImpact;
  if (level === "Medium") return t.mediumImpact;
  return t.highImpact;
}

export function getCoverLabel(level, language) {
  return getTranslations(language)[level.toLowerCase()] ?? level;
}

export function formatLastUpdated(value, language) {
  const locale = language === "sw" ? "sw-KE" : "en-KE";
  return new Intl.DateTimeFormat(locale, {
    day: "numeric",
    month: "short",
    year: "numeric",
    hour: "numeric",
    minute: "2-digit",
  }).format(new Date(value));
}
